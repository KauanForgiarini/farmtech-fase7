-- FarmTech Solutions - mesmo modelo do Oracle (01_ddl_farmtech.sql) em SQLite.
-- Usado quando FARMTECH_DB=sqlite (padrão), para o sistema rodar sem a rede da FIAP.

CREATE TABLE CULTURA (
    ID_CULTURA      INTEGER PRIMARY KEY,
    NOME            TEXT    NOT NULL UNIQUE,
    PH_MIN          REAL    NOT NULL,
    PH_MAX          REAL    NOT NULL,
    UMIDADE_MIN     REAL    NOT NULL,
    UMIDADE_MAX     REAL    NOT NULL,
    ESPACAMENTO_M   REAL    NOT NULL,
    CHECK (PH_MIN < PH_MAX)
);

CREATE TABLE TALHAO (
    ID_TALHAO        INTEGER PRIMARY KEY,
    NOME             TEXT    NOT NULL,
    ID_CULTURA       INTEGER NOT NULL REFERENCES CULTURA (ID_CULTURA),
    FORMA            TEXT    NOT NULL CHECK (FORMA IN ('RETANGULO', 'CIRCULO')),
    DIMENSAO_1_M     REAL    NOT NULL,
    DIMENSAO_2_M     REAL,
    AREA_M2          REAL    NOT NULL CHECK (AREA_M2 > 0),
    AREA_HA          REAL    NOT NULL,
    NUM_RUAS         INTEGER,
    METROS_LINEARES  REAL,
    DATA_CADASTRO    TEXT
);

CREATE TABLE APLICACAO_INSUMO (
    ID_APLICACAO      INTEGER PRIMARY KEY,
    ID_TALHAO         INTEGER NOT NULL REFERENCES TALHAO (ID_TALHAO) ON DELETE CASCADE,
    INSUMO            TEXT    NOT NULL,
    TIPO_DOSE         TEXT    NOT NULL CHECK (TIPO_DOSE IN ('POR_HA', 'POR_METRO')),
    DOSE              REAL    NOT NULL,
    UNIDADE           TEXT    NOT NULL,
    QUANTIDADE_TOTAL  REAL    NOT NULL,
    UNIDADE_TOTAL     TEXT    NOT NULL
);

CREATE TABLE LEITURA_SENSOR (
    ID_LEITURA         INTEGER PRIMARY KEY,
    ID_TALHAO          INTEGER NOT NULL REFERENCES TALHAO (ID_TALHAO),
    DATA_HORA          TEXT    NOT NULL,
    N_PRESENTE         INTEGER CHECK (N_PRESENTE IN (0, 1)),
    P_PRESENTE         INTEGER CHECK (P_PRESENTE IN (0, 1)),
    K_PRESENTE         INTEGER CHECK (K_PRESENTE IN (0, 1)),
    N_KGHA             REAL,
    P_KGHA             REAL,
    K_KGHA             REAL,
    PH_SOLO            REAL    CHECK (PH_SOLO BETWEEN 0 AND 14),
    UMIDADE_SOLO_PCT   REAL    CHECK (UMIDADE_SOLO_PCT BETWEEN 0 AND 100),
    TEMPERATURA_C      REAL,
    CHUVA_PREVISTA_MM  REAL,
    BOMBA_LIGADA       INTEGER CHECK (BOMBA_LIGADA IN (0, 1)),
    MOTIVO_DECISAO     TEXT,
    ORIGEM             TEXT
);

CREATE TABLE PREVISAO_ML (
    ID_LEITURA                INTEGER PRIMARY KEY
                              REFERENCES LEITURA_SENSOR (ID_LEITURA) ON DELETE CASCADE,
    VOLUME_IRRIGACAO_L        REAL,
    NECESSIDADE_FERT_KGHA     REAL,
    RENDIMENTO_ESPERADO_SCHA  REAL,
    MODELO                    TEXT
);

CREATE TABLE DETECCAO_VISAO (
    ID_DETECCAO   INTEGER PRIMARY KEY,
    DATA_HORA     TEXT    NOT NULL,
    LOCAL_CAMERA  TEXT    NOT NULL,
    IMAGEM        TEXT    NOT NULL,
    CLASSE        TEXT    NOT NULL,
    CONFIANCA     REAL    CHECK (CONFIANCA BETWEEN 0 AND 1),
    X1            REAL,
    Y1            REAL,
    X2            REAL,
    Y2            REAL,
    MODELO        TEXT
);

CREATE TABLE ALERTA (
    ID_ALERTA       INTEGER PRIMARY KEY,
    DATA_HORA       TEXT    NOT NULL,
    ORIGEM          TEXT    NOT NULL,
    CODIGO          TEXT    NOT NULL,
    SEVERIDADE      TEXT    NOT NULL CHECK (SEVERIDADE IN ('INFO', 'MEDIO', 'ALTO', 'CRITICO')),
    TITULO          TEXT    NOT NULL,
    LOCAL_ALERTA    TEXT,
    EVIDENCIA       TEXT,
    ACAO_CORRETIVA  TEXT    NOT NULL,
    RESPONSAVEL     TEXT,
    OCORRENCIAS     INTEGER,
    CANAL           TEXT,
    STATUS_ENVIO    TEXT,
    MESSAGE_ID      TEXT
);

CREATE INDEX IX_LEITURA_DATA ON LEITURA_SENSOR (DATA_HORA);
CREATE INDEX IX_DETECCAO_CLASSE ON DETECCAO_VISAO (CLASSE);
CREATE INDEX IX_ALERTA_SEVERIDADE ON ALERTA (SEVERIDADE);
